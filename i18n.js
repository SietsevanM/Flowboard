  function interpolate(text, params) {
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, function (match, key) {
      return params[key] != null ? String(params[key]) : match;
    });
  }

  function t(key, params) {
    return tForLocale(currentLocale, key, params);
  }

  function tForLocale(locale, key, params) {
    var localeMessages = messages[locale] || messages.en;
    var text = localeMessages[key];
    if (text == null) text = messages.en[key];
    if (text == null) return key;
    return interpolate(text, params);
  }

  function getLocale() {
    return currentLocale;
  }

  function detectLocale() {
    try {
      var stored = localStorage.getItem(STORAGE_KEY);
      if (stored && SUPPORTED.indexOf(stored) !== -1) return stored;
    } catch (e) { /* ignore */ }
    var browser = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return SUPPORTED.indexOf(browser) !== -1 ? browser : 'en';
  }

  function applyI18nToDOM(root) {
    var scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      el.title = t(el.getAttribute('data-i18n-title'));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
    document.title = t('app.title');
  }

  function setLocale(code) {
    if (SUPPORTED.indexOf(code) === -1) code = 'en';
    if (code === currentLocale) return;
    currentLocale = code;
    try {
      localStorage.setItem(STORAGE_KEY, code);
    } catch (e) { /* ignore */ }
    document.documentElement.lang = code;
    applyI18nToDOM();
    if (typeof onLocaleChange === 'function') onLocaleChange(code);
  }

  function init() {
    currentLocale = detectLocale();
    document.documentElement.lang = currentLocale;
    applyI18nToDOM();
  }

  global.FlowboardI18n = {
    t: t,
    tForLocale: tForLocale,
    getLocale: getLocale,
    setLocale: setLocale,
    applyI18nToDOM: applyI18nToDOM,
    init: init,
    get supportedLocales() { return SUPPORTED.slice(); },
    set onLocaleChange(fn) { onLocaleChange = fn; },
  };
